"""
report.py
---------
Regenerates models/model_card.md from the real artefacts (metrics_report.json,
feature_importance.csv, scored_customers.csv, the raw datasets). Nothing in the
card is typed by hand, so the documented numbers cannot drift from the results.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from features import ROOT


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def main() -> None:
    models, reports, ds = ROOT / "models", ROOT / "reports", ROOT / "datasets"
    m = json.loads((models / "metrics_report.json").read_text())
    imp = pd.read_csv(models / "feature_importance.csv")
    scored = pd.read_csv(models / "scored_customers.csv")
    thr = pd.read_csv(reports / "threshold_analysis.csv")
    sc, split, calib = m["success_scorecard"], m["split"], m["calibration"]
    at05, atop, bands = m["champion_test_at_0.5_raw"], m["champion_test_at_operating_threshold"], m["bands"]
    cands = m["all_candidates"]

    # temporal facts about the source data (disclosed limitation)
    loans = pd.read_csv(ds / "loan_applications.csv", parse_dates=["application_date"])
    disb = loans[loans["loan_default"].notna()]
    snap = pd.to_datetime(pd.read_csv(ds / "credit_history.csv")["as_of_date"]).max()
    txn_start = pd.to_datetime(pd.read_csv(ds / "transactions.csv")["transaction_date"]).min()
    pct_before_snap = (disb["application_date"] < snap).mean()
    pct_before_txn = (disb["application_date"] < txn_start).mean()

    cand_tbl = pd.DataFrame([{
        "Model": ("**" + c["model"] + "**") if c["model"] == m["champion_model"] else c["model"],
        "CV ROC-AUC (train, grouped 5-fold)": f"{c['cv_roc_auc_mean']:.3f} +/- {c['cv_roc_auc_std']:.3f}",
        "Test ROC-AUC": f"{c['roc_auc']:.3f}",
        "Recall @0.5": f"{c['recall']:.3f}",
        "Precision @0.5": f"{c['precision']:.3f}",
        "Best params": ", ".join(f"{k}={v}" for k, v in c["best_params"].items()),
    } for c in cands])

    band_tbl = pd.DataFrame([{
        "Band": b["band"], "Test loans": b["loans"], "Share": f"{b['share_of_loans']:.1%}",
        "Observed default rate": f"{b['observed_default_rate']:.1%}"} for b in m["band_validation_test"]])

    thr_tbl = thr.assign(**{c: thr[c].round(3) for c in ["precision", "recall", "f1", "flagged_share"]})
    thr_tbl = thr_tbl[["threshold", "recall", "precision", "f1", "flagged_share"]]
    thr_tbl.columns = ["Threshold", "Recall", "Precision", "F1", "Share of loans flagged"]

    imp_tbl = imp.head(10)[["rank", "feature", "mean_abs_shap"]].assign(mean_abs_shap=lambda d: d["mean_abs_shap"].round(3))
    imp_tbl.columns = ["Rank", "Feature", "Mean |SHAP| (log-odds)"]

    basis = scored.groupby("score_basis").agg(customers=("customer_id", "count"),
                                              mean_p=("default_probability", "mean"),
                                              high=("risk_category", lambda s: (s == "High Risk").mean()))
    basis_tbl = pd.DataFrame({"Score basis": basis.index, "Customers": basis["customers"].values,
                              "Mean P(default)": basis["mean_p"].round(3).values,
                              "Share High Risk": [f"{v:.1%}" for v in basis["high"].values]})

    auc_lo, auc_hi = min(c["roc_auc"] for c in cands), max(c["roc_auc"] for c in cands)
    ci = sc["recall_ci95_at_operating_threshold"]
    cm = atop["confusion_matrix"]

    def ok(flag): return "Met" if flag else "**Not met**"

    card = f"""# Model Card - Credora Loan-Default Classifier

*Generated by `src/report.py` from `models/metrics_report.json`; do not edit by hand.*

**Project:** Credit Risk & Loan Approval Analytics Platform | **Owner:** Data & Analytics Team, Credora Finance

## 1. Overview

| | |
|---|---|
| **Task** | Binary classification - P(`loan_default`) for a disbursed loan |
| **Champion** | {m['champion_model']} (tuned), followed by Platt probability calibration |
| **Selection rule** | {m['selection_rule']} |
| **Population** | Disbursed loans with an observed outcome (n = {split['train_loans'] + split['test_loans']:,}) |
| **Split** | 80/20 stratified, **grouped by customer** - train {split['train_loans']:,} loans / {split['train_customers']:,} customers; test {split['test_loans']:,} loans / {split['test_customers']:,} customers; customers in both: {split['customers_shared']} |
| **Features** | {m['n_features']} (credit bureau, application, demographic, 6-month transaction aggregates) |
| **Artefacts** | `models/default_model.pkl`, `models/risk_bands.json`, `models/feature_importance.csv` |

## 2. Method

1. **Grouped split.** A customer can hold several loans; the split keeps all of a customer's loans on one side so the test score is not inflated by the same borrower appearing in train.
2. **Hyperparameter search.** `RandomizedSearchCV`, 5-fold `StratifiedGroupKFold`, scoring ROC-AUC, on the training set only, for all four algorithms.
3. **Champion chosen on cross-validated ROC-AUC** - the test set is evaluated once, after selection.
4. **Calibration.** `class_weight='balanced'` lifts raw probabilities (mean {calib['mean_predicted_raw']:.3f} vs an actual default rate of {calib['actual_default_rate']:.3f}). A 2-parameter sigmoid fitted on out-of-fold training predictions brings the mean to {calib['mean_predicted_calibrated']:.3f}; Brier score {calib['brier_raw']:.3f} -> {calib['brier_calibrated']:.3f}.
5. **Operating threshold.** Chosen on out-of-fold training predictions as the highest threshold that still catches >= 70% of defaulters: **{bands['operating_threshold']:.3f}**. Not tuned on the test set.
6. **Risk bands.** `risk_score = round(P x 100)`. Low < {bands['low_below']}, Medium {bands['low_below']}-{bands['high_from'] - 1}, High >= {bands['high_from']}. The PRD's default 33/66 cut-offs assume probabilities that reach 0.66; calibrated probabilities on a 23% default book almost never do, so the PRD-sanctioned "tune against the confusion matrix" step was applied. Low = the band that holds at most ~10% of defaulters.

## 3. Candidates (all tuned)

{md_table(cand_tbl)}

All four tuned algorithms land between {auc_lo:.3f} and {auc_hi:.3f} test ROC-AUC. That the ranking barely moves across a linear model, a tree, a forest and gradient boosting points to a ceiling set by the data, not by the algorithm.

## 4. Champion performance on the held-out test set ({split['test_loans']} loans, {sc['test_defaulters']} defaulters)

| | ROC-AUC | Recall | Precision | F1 |
|---|---|---|---|---|
| Raw probabilities, threshold 0.50 | {at05['roc_auc']:.3f} | {at05['recall']:.3f} | {at05['precision']:.3f} | {at05['f1']:.3f} |
| **Calibrated, operating threshold {bands['operating_threshold']:.3f}** | {atop['roc_auc']:.3f} | **{atop['recall']:.3f}** | {atop['precision']:.3f} | {atop['f1']:.3f} |

Confusion matrix at the operating threshold:

| | Predicted: no default | Predicted: default |
|---|---|---|
| **Actual: no default** | {cm[0][0]} | {cm[0][1]} |
| **Actual: default** | {cm[1][0]} | {cm[1][1]} |

Recall/precision across thresholds (calibrated probabilities, test set):

{md_table(thr_tbl)}

**Do the bands rank risk correctly?** Yes - observed default rate rises monotonically across bands on unseen loans:

{md_table(band_tbl)}

Figures: `reports/figures/` (ROC curves, calibration, confusion matrix, threshold trade-off, SHAP summary).

## 5. Against the PRD success targets (section 16)

| Target | Result | Status |
|---|---|---|
| ROC-AUC >= {sc['roc_auc_target']:.2f} | {sc['roc_auc_achieved']:.3f} | {ok(sc['roc_auc_met'])} |
| Recall on defaulters >= {sc['recall_target']:.2f} | {sc['recall_at_operating_threshold']:.3f} at the operating threshold (95% CI {ci[0]:.2f}-{ci[1]:.2f}); {sc['recall_at_default_0.5']:.3f} at the naive 0.50 threshold | {ok(sc['recall_met'])} on the point estimate; the target {'lies inside' if sc['recall_target_inside_ci95'] else 'lies outside'} the 95% interval |
| Training < 5 min on a laptop | {sc['training_seconds']} s | {ok(sc['training_under_5_min'])} |

We did **not** lower the threshold after seeing the test result to make recall cross 0.70: that would be tuning on the test set. With only {sc['test_defaulters']} defaulters in the test set, a recall of {sc['recall_at_operating_threshold']:.3f} cannot be told apart statistically from 0.70.

## 6. What drives predictions (SHAP)

{md_table(imp_tbl)}

Full ranking: `models/feature_importance.csv`; per-customer drivers: `top_risk_drivers` in `models/scored_customers.csv`. Contributions are log-odds of the base model; calibration is monotonic so their sign and rank are unchanged.

## 7. Who gets scored, and how much to trust each score

{md_table(basis_tbl)}

- `disbursed_loan`: out-of-fold probability, the most trustworthy score (the model never saw that customer).
- `application_not_disbursed`: the model learned only from disbursed loans, so these (largely applicants the bank itself rejected) are extrapolations. A high average here is expected, not proof of accuracy.
- `reference_loan`: the customer never applied; scored against a typical reference loan. It answers "how risky on a standard loan?", not "how risky is a real application?".

## 8. Known limitations

- **Discrimination ceiling.** ROC-AUC {sc['roc_auc_achieved']:.2f} vs the 0.80 target. Four tuned algorithms agree, so closing the gap needs better data (longer transaction history, bureau time series, more disbursed loans), not a fancier model.
- **Time ordering of the source data.** The single bureau snapshot is dated {snap.date()}, after {pct_before_snap:.0%} of disbursed applications; the transaction window starts {txn_start.date()}, after {pct_before_txn:.0%} of them. For many loans the features were observed after the outcome. This comes from how the dataset is built, so it cannot be fixed here, but it means reported metrics are optimistic relative to a true point-in-time model. An out-of-time validation is the first thing to add with real data.
- **Selection bias.** Trained on disbursed loans only (reject inference not attempted).
- **Synthetic data.** Credora Finance is fictional; the pipeline and evaluation discipline are the deliverable, not a claim about a real book.
- **Fairness.** No bias review (PRD non-goal). gender, marital_status, city, state, loan_purpose and kyc_status are excluded from the model as inputs.
- **Static model.** No retraining or drift monitoring (PRD section 19).

## 9. Leakage and privacy controls

Excluded as post-decision information: `approval_status`, `approved_amount`, `decision_date`, `disbursed_flag`. Excluded for privacy: names, `email`, `phone`. Transactions are aggregated to one row per customer before joining. Unbounded ratios (`txn_inflow_outflow_ratio`, `loan_to_income_ratio`) are capped so extreme customers cannot make the linear model extrapolate.

## 10. Intended use

Advisory only: a probability and a 0-100 score shown to a human underwriter beside the bureau score. It does not approve, reject or price a loan, and is not validated for real lending decisions.
"""
    (models / "model_card.md").write_text(card, encoding="utf-8")
    print(f"Wrote {models / 'model_card.md'} ({len(card.splitlines())} lines)")


if __name__ == "__main__":
    main()
